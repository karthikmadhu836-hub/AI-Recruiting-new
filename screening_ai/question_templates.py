def generate_skill_question(role):

    return (
        f"What are your key skills "
        f"relevant to the {role} role?"
    )


def generate_experience_question(role):

    return (
        f"Can you describe your experience "
        f"related to the {role} position?"
    )


def generate_location_question():

    return (
        "Are you open to relocation "
        "or remote work?"
    )


def generate_salary_question():

    return (
        "What are your salary expectations?"
    )


def generate_notice_question():

    return (
        "What is your notice period?"
    )